// Regenerates the display page's Noto Sans SC MSDF subset for @react-three/uikit.
// Setup once: npm ci --ignore-scripts --prefix scripts/fonts
// Usage:      node scripts/fonts/generate-sc-font.ts
import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { CHARSET_FILE, FALLBACK_GLYPH, REPO_ROOT, requiredCharset } from "./charset.ts";
import { CACHE_DIR, fetchVerified, loadSources } from "./sources.ts";

const FONT_SIZE = 32;
const DISTANCE_RANGE = 4;
const BASENAME = `noto-sans-sc-${String(FONT_SIZE)}`;
const OUTPUT_DIR = path.join(REPO_ROOT, "apps/web-display/public/fonts/noto-sans-sc");
const GLYPHS_MODULE = path.join(REPO_ROOT, "apps/web-display/src/model/sc-glyphs.ts");
const CLI = path.join(REPO_ROOT, "scripts/fonts/node_modules/msdf-bmfont-xml/cli.js");

interface BmFont {
  pages: string[];
  chars: { char: string }[];
  info: Record<string, unknown>;
  common: { pages: number; scaleW: number; scaleH: number };
}

const sources = await loadSources();
const fontFile = await fetchVerified(sources.font);
const licenseFile = await fetchVerified(sources.license);

const charset = requiredCharset();
await writeFile(CHARSET_FILE, `${charset.join("")}\n`);

const work = await mkdtemp(path.join(CACHE_DIR, "work-"));
try {
  await writeFile(path.join(work, "charset.txt"), charset.join(""));
  await symlink(fontFile, path.join(work, "font.otf"));
  execFileSync(
    process.execPath,
    [
      CLI,
      ...["--output-type", "json", "--filename", BASENAME, "--charset-file", "charset.txt"],
      ...["--font-size", String(FONT_SIZE), "--distance-range", String(DISTANCE_RANGE), "--field-type", "msdf"],
      ...["--texture-padding", "2", "--texture-size", "2048,2048", "--smart-size", "--pot", "font.otf"],
    ],
    { cwd: work, stdio: ["ignore", "ignore", "inherit"] },
  );
  const font = JSON.parse(await readFile(path.join(work, "font.json"), "utf8")) as BmFont;
  if (font.pages.length !== 1 || font.common.pages !== 1) throw new Error("uikit needs exactly one atlas page");

  const glyphs = new Set(font.chars.map((glyph) => glyph.char));
  const missing = charset.filter((char) => !glyphs.has(char));
  if (missing.length > 0) throw new Error(`font lacks required characters: ${missing.join("")}`);
  if (!glyphs.has(FALLBACK_GLYPH)) throw new Error("fallback glyph missing");

  // The CLI adds an empty space glyph even when the charset already has one.
  font.chars = font.chars.filter(
    (glyph, index) => font.chars.findIndex((other) => other.char === glyph.char) === index,
  );
  // uikit resolves the page relative to the JSON URL and never reads info.charset.
  font.pages = [`${BASENAME}.png`];
  delete font.info.charset;
  font.info.face = "Noto Sans SC";

  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(path.join(OUTPUT_DIR, `${BASENAME}.json`), JSON.stringify(font));
  await copyFile(path.join(work, `${BASENAME}.png`), path.join(OUTPUT_DIR, `${BASENAME}.png`));
  await copyFile(licenseFile, path.join(OUTPUT_DIR, "LICENSE"));

  const sorted = [...glyphs].sort((a, b) => (a.codePointAt(0) ?? 0) - (b.codePointAt(0) ?? 0)).join("");
  await writeFile(
    GLYPHS_MODULE,
    [
      "// Generated by scripts/fonts/generate-sc-font.ts from the font JSON; do not edit.",
      "export const SC_FONT_GLYPHS =",
      `  ${JSON.stringify(sorted)};`,
      "",
    ].join("\n"),
  );
  console.log(`${String(glyphs.size)} glyphs, atlas ${String(font.common.scaleW)}x${String(font.common.scaleH)}`);
} finally {
  await rm(work, { recursive: true, force: true });
}
